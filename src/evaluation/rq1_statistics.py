"""RQ1 benchmark statistics and Table 3 export.

Computes the RQ1 benchmark-statistics table (``tables/table3_benchmark_statistics.csv``/``.tex``,
generated by ``scripts/run_rq1.py``): per-dataset requirement/code/link
counts and the FR/NFR/Mixed requirement-type distribution, including
``Is_No_Code`` requirements that are excluded from the main traceability
evaluation. This module answers "how are requirement types distributed"
independent of any retrieval method's performance; it does not compute or
depend on any baseline or framework score.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from ..data.loader import DatasetLoader, TraceDataset
from ..utils import ensure_directory


STAT_COLUMNS = [
    "Dataset",
    "Scope",
    "Req.",
    "Code",
    "FR",
    "NFR",
    "Mixed",
    "No-code Req.",
    "Links",
]


def dataset_statistics(dataset: TraceDataset) -> dict[str, object]:
    type_counts = pd.Series(
        [requirement.req_type for requirement in dataset.requirements.values()]
    ).value_counts()
    return {
        "Dataset": dataset.name,
        "Scope": dataset.scope,
        "Req.": len(dataset.requirements),
        "Code": len(dataset.code_files),
        "FR": int(type_counts.get("FR", 0)),
        "NFR": int(type_counts.get("NFR", 0)),
        "Mixed": int(type_counts.get("Mixed", 0)),
        "No-code Req.": sum(
            requirement.is_no_code for requirement in dataset.requirements.values()
        ),
        "Links": len(dataset.trace_links),
    }


def build_statistics(loader: DatasetLoader) -> pd.DataFrame:
    rows = [dataset_statistics(loader.load(name)) for name in loader.dataset_names]
    total = {
        "Dataset": "Total",
        "Scope": "--",
        **{
            column: sum(int(row[column]) for row in rows)
            for column in STAT_COLUMNS[2:]
        },
    }
    return pd.DataFrame([*rows, total], columns=STAT_COLUMNS)


def to_latex_table(frame: pd.DataFrame) -> str:
    rows: list[str] = [
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Statistics of the constructed benchmark after annotation.}",
        r"\label{tab:dataset_statistics}",
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r"Dataset & Scope & Req. & Code & FR & NFR & Mixed & No-code Req. & Links \\",
        r"\midrule",
    ]
    for index, row in frame.iterrows():
        if row["Dataset"] == "Total":
            rows.append(r"\midrule")
        rows.append(
            "{} & {} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
                *[row[column] for column in STAT_COLUMNS]
            )
        )
    rows.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""])
    return "\n".join(rows)


def export_statistics(
    frame: pd.DataFrame, tables_dir: str | Path
) -> tuple[Path, Path]:
    output_dir = ensure_directory(Path(tables_dir))
    csv_path = output_dir / "table3_benchmark_statistics.csv"
    latex_path = output_dir / "table3_benchmark_statistics.tex"
    frame.to_csv(csv_path, index=False, encoding="utf-8")
    latex_path.write_text(to_latex_table(frame), encoding="utf-8")
    return csv_path, latex_path
